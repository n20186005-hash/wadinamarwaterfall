export function getTopic(slug: string): Topic | undefined {
  return TOPICS.find((t) => t.slug === slug);
}

export function topicSlugs(): string[] {
  return TOPICS.map((t) => t.slug);
}

export function topicsByGroup(group: TopicGroup): Topic[] {
  return TOPICS.filter((t) => t.group === group);
}

export function getRelatedTopics(slug: string): Topic[] {
  const topic = getTopic(slug);
  if (!topic) return [];
  return topic.related.map((r) => getTopic(r)).filter((t): t is Topic => Boolean(t));
}
